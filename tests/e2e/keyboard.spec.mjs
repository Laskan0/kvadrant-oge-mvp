import { test, expect } from '@playwright/test'

test('клавиатура, фокус, маленькая область просмотра и перезагрузка', async ({ page, browserName }) => {
  const tab = () => page.keyboard.press(browserName === 'webkit' ? 'Alt+Tab' : 'Tab')
  await page.goto('/')
  await tab()
  const start = page.getByRole('button', { name: 'Начать обучение' })
  await expect(start).toBeFocused()
  const focus = await start.evaluate(element => ({ outline: getComputedStyle(element).outlineStyle, width: getComputedStyle(element).outlineWidth }))
  expect(focus.outline).not.toBe('none')
  expect(parseFloat(focus.width)).toBeGreaterThanOrEqual(2)
  await page.keyboard.press('Enter')
  await page.getByRole('heading', { name: 'Узнай коэффициенты' }).waitFor()
  // После перехода фокус на основной области, Tab входит в первую radio-группу.
  await tab()
  await expect(page.getByRole('group', { name: 'Коэффициент a' }).getByRole('radio', { name: '0', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await tab()
  await page.keyboard.press('ArrowRight')
  await tab()
  await page.keyboard.press('Space')
  await tab()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Далее', exact: true })).toBeEnabled()
  await tab()
  await page.keyboard.press('Enter')
  await page.getByRole('heading', { name: 'Вычисли дискриминант' }).waitFor()
  await tab()
  const input = page.getByRole('textbox')
  await expect(input).toBeFocused()
  await page.keyboard.type('4')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Далее', exact: true })).toBeEnabled()
  const original = page.viewportSize()
  // Моделируем уменьшение доступной высоты, а не настоящую экранную клавиатуру iOS.
  await page.setViewportSize({ width: original.width, height: 360 })
  await input.scrollIntoViewIfNeeded()
  const inputBox = await input.boundingBox()
  expect(inputBox.y).toBeGreaterThanOrEqual(0)
  expect(inputBox.y + inputBox.height).toBeLessThanOrEqual(360)
  await tab()
  await expect(page.getByRole('button', { name: 'Проверить D', exact: true })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  const motion = await page.locator('.ship-idle').evaluate(element => getComputedStyle(element).animationName)
  expect(motion).toBe('none')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'КВАДРАНТ', exact: true })).toBeVisible()
})
