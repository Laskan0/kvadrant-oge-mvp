test('знакомство меняет выражение БИПа, а в уроке он остаётся рядом с объяснением', async ({ page }) => {
  await page.goto('/')
  const bip = page.locator('.computer-icon')
  await expect(page.locator('.briefing-dialogue [data-expression="friendly"]')).toBeVisible()
  await page.getByRole('button', { name: 'Далее', exact: false }).click()
  await expect(page.locator('.briefing-dialogue [data-expression="thinking"]')).toBeVisible()
  await page.getByRole('button', { name: 'Далее', exact: false }).click()
  await expect(page.locator('.briefing-dialogue [data-expression="encouraging"]')).toBeVisible()
  await page.getByRole('button', { name: 'Назад', exact: true }).click()
  await expect(page.locator('.briefing-dialogue [data-expression="thinking"]')).toBeVisible()
  await page.getByRole('button', { name: 'Далее', exact: false }).click()
  await page.getByRole('button', { name: 'Далее', exact: false }).click()
  await page.getByRole('button', { name: 'Начать обучение' }).click()
  await page.getByRole('heading', { name: 'Узнай коэффициенты' }).waitFor()
  const x0 = (await bip.boundingBox()).x
  await page.getByRole('group', { name: 'Коэффициент a' }).getByRole('radio', { name: '1', exact: true }).check()
  await page.getByRole('group', { name: 'Коэффициент b' }).getByRole('radio', { name: '−4', exact: true }).check()
  await page.getByRole('group', { name: 'Коэффициент c' }).getByRole('radio', { name: '3', exact: true }).check()
  await page.getByRole('button', { name: 'Проверить коэффициенты' }).click()
  await page.getByRole('button', { name: 'Далее', exact: true }).click()
  const x1 = (await bip.boundingBox()).x
  expect(Math.abs(x1 - x0)).toBeLessThan(2)
  expect(await page.locator('.lesson-guide .computer p').count()).toBe(1)
})

test('приборная панель следует за космической сценой и складывается на мобильном экране', async ({ page }) => {
  await page.goto('/')
  await completeBriefing(page)
  await page.getByRole('button', { name: 'Начать обучение' }).click()
  await page.getByRole('heading', { name: 'Узнай коэффициенты' }).waitFor()
  await page.getByRole('group', { name: 'Коэффициент a' }).getByRole('radio', { name: '1', exact: true }).check()
  await page.getByRole('group', { name: 'Коэффициент b' }).getByRole('radio', { name: '−4', exact: true }).check()
  await page.getByRole('group', { name: 'Коэффициент c' }).getByRole('radio', { name: '3', exact: true }).check()
  await page.getByRole('button', { name: 'Проверить коэффициенты' }).click()
  await page.getByRole('button', { name: 'Далее', exact: true }).click()
  await page.getByRole('textbox', { name: 'D = 16 − 12 =' }).fill('4')
  await page.getByRole('button', { name: 'Проверить D' }).click()
  await page.getByRole('button', { name: 'Далее', exact: true }).click()
  for (const c of [3, 4, 5]) await page.getByRole('button', { name: `c = ${c}`, exact: false }).click()
  await expect(page.locator('.graph-learning-note')).toContainText('точки пересечения параболы с осью X')
  await page.getByRole('button', { name: 'Далее', exact: true }).click()
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Показать следующий шаг' }).click()
  await expect(page.locator('.root-stage-row').last()).toContainText('3. Получаем два значения')
  await expect(page.locator('.root-stage-row').last().locator('.root-stage-bip')).toBeVisible()
  const lastRootStep = await page.locator('.root-stage-row').last().locator('.root-step').boundingBox()
  const lastRootBip = await page.locator('.root-stage-row').last().locator('.root-stage-bip').boundingBox()
  if (page.viewportSize().width > 600) expect(lastRootBip.x).toBeGreaterThan(lastRootStep.x + lastRootStep.width)
  await page.getByRole('button', { name: 'Далее', exact: true }).click()
  await page.getByRole('radio', { name: 'D = 4; корни 1 и 3', exact: true }).check()
  await page.getByRole('button', { name: 'Подтвердить', exact: true }).click()
  await page.getByRole('button', { name: 'К маршруту', exact: true }).click()
  await page.getByRole('heading', { name: 'Первая точка маршрута' }).waitFor()
  const scene = await page.locator('.space-scene').boundingBox()
  const dashboard = await page.locator('.cockpit-dashboard').boundingBox()
  const comms = await page.locator('.bip-comms').boundingBox()
  const controls = await page.locator('.cockpit-controls').boundingBox()
  const ship = await page.locator('.ship').boundingBox()
  expect(scene.height).toBeGreaterThanOrEqual(320)
  expect(dashboard.y).toBeGreaterThanOrEqual(scene.y + scene.height)
  if (page.viewportSize().width <= 640) {
    expect(comms.y).toBeLessThan(controls.y)
    expect(ship.x).toBeGreaterThanOrEqual(scene.x)
    expect(ship.x + ship.width).toBeLessThanOrEqual(scene.x + scene.width)
  }
  else expect(comms.x).toBeLessThan(controls.x)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('полный путь, ошибки, подсказки, разбор, повторы и доступность', async ({ page }) => {
  const scan = async () => {
    const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
    expect(result.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([])
  }
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',m=>{if(['error','warning'].includes(m.type()))errors.push(m.text())})
  const noOverflow=async()=>assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  const next=()=>page.getByRole('button',{name:'Далее',exact:true})
  await page.goto('/')
  await expect(page).toHaveTitle('КВАДРАНТ — квадратные уравнения')
  await scan()
  await completeBriefing(page)
  await page.getByRole('button',{name:'Начать обучение'}).click()
  await page.getByRole('heading',{name:'Узнай коэффициенты'}).waitFor()
  assert.ok(await next().isDisabled())
  await page.getByRole('button',{name:'Проверить коэффициенты'}).click()
  await page.getByRole('status').filter({hasText:'Выбери значение'}).waitFor()
  await page.getByRole('group',{name:'Коэффициент a'}).getByRole('radio',{name:'1',exact:true}).check()
  await page.getByRole('group',{name:'Коэффициент b'}).getByRole('radio',{name:'4',exact:true}).check()
  await page.getByRole('group',{name:'Коэффициент c'}).getByRole('radio',{name:'3',exact:true}).check()
  await page.getByRole('button',{name:'Проверить коэффициенты'}).click()
  assert.ok(await next().isDisabled())
  await page.getByRole('group',{name:'Коэффициент b'}).getByRole('radio',{name:'−4',exact:true}).check()
  await page.getByRole('button',{name:'Проверить коэффициенты'}).click()
  assert.ok(await next().isEnabled())
  await noOverflow()
  await next().click()
  await page.getByRole('textbox',{name:'D = 16 − 12 ='}).fill('-4')
  await page.getByRole('button',{name:'Проверить D',exact:true}).click()
  assert.ok(await next().isDisabled())
  await page.getByRole('textbox').fill('4,0')
  await page.getByRole('textbox').press('Enter')
  assert.ok(await next().isEnabled())
  await page.getByRole('button',{name:'Назад',exact:true}).click()
  assert.ok(await page.getByRole('group',{name:'Коэффициент b'}).getByRole('radio',{name:'−4',exact:true}).isChecked())
  await next().click()
  assert.equal(await page.getByRole('textbox').inputValue(),'4,0')
  assert.ok(await next().isEnabled())
  await next().click()
  assert.ok(await next().isDisabled())
  assert.equal(await page.getByTestId('graph-root').count(),2)
  const firstPath=await page.getByTestId('parabola').getAttribute('points')
  await page.getByRole('button',{name:'c = 4',exact:false}).click()
  assert.equal(await page.getByTestId('graph-root').count(),1)
  assert.notEqual(await page.getByTestId('parabola').getAttribute('points'),firstPath)
  assert.ok(await next().isDisabled())
  await page.getByRole('button',{name:'c = 5',exact:false}).click()
  assert.equal(await page.getByTestId('graph-root').count(),0)
  assert.ok(await next().isEnabled())
  await noOverflow()
  await scan()
  await next().click()
  assert.ok(await next().isDisabled())
  for(let i=0;i<3;i++)await page.getByRole('button',{name:'Показать следующий шаг'}).click()
  assert.equal(await page.locator('.root-step').count(),3)
  assert.equal(await page.locator('.katex-error').count(),0)
  assert.ok(await next().isEnabled())
  await noOverflow()
  await scan()
  await page.getByRole('button',{name:'Назад',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'c = 5',exact:false}).getAttribute('aria-pressed'),'true')
  assert.ok(await next().isEnabled())
  await next().click()
  assert.equal(await page.locator('.root-step').count(),3)
  await next().click()
  await page.getByRole('radio',{name:'D = 4; корни −1 и −3',exact:true}).check()
  await page.getByRole('button',{name:'Подтвердить',exact:true}).click()
  assert.ok(await page.getByRole('button',{name:'К маршруту',exact:true}).isDisabled())
  await page.getByRole('radio',{name:'D = 4; корни 1 и 3',exact:true}).check()
  await page.getByRole('button',{name:'Подтвердить',exact:true}).click()
  await page.getByRole('button',{name:'К маршруту',exact:true}).click()

  await page.getByRole('heading',{name:'Первая точка маршрута'}).waitFor()
  const d=()=>page.getByRole('textbox',{name:'Дискриминант D',exact:true})
  const r1=()=>page.getByRole('textbox',{name:'Первый корень x₁',exact:true})
  const r2=()=>page.getByRole('textbox',{name:'Второй корень x₂',exact:true})
  const checkD=()=>page.getByRole('button',{name:'Проверить D',exact:true})
  const checkRoots=()=>page.getByRole('button',{name:'Проверить корни',exact:true})
  await checkD().click()
  await page.getByRole('status').filter({hasText:'Введи значение D.'}).waitFor()
  assert.equal(await r1().count(),0)
  await d().fill('abc')
  await checkD().click()
  await page.getByRole('status').filter({hasText:'Введи число.'}).waitFor()
  await d().fill('-1')
  await checkD().click()
  assert.equal(await r1().count(),0)
  assert.equal(await page.locator('.terminal-warning').count(),1)
  await scan()
  await page.getByRole('button',{name:'Подсказка',exact:true}).click()
  await page.getByRole('button',{name:'Ещё подсказка',exact:true}).click()
  assert.equal(await page.locator('.practice-hints li').count(),2)
  await page.getByRole('button',{name:'Показать полный разбор',exact:true}).click()
  assert.equal(await d().inputValue(),'-1')
  assert.equal(await r1().count(),0)
  assert.equal(await page.locator('.full-solution').count(),1)
  await noOverflow()
  await scan()
  await d().fill('1,0')
  await d().press('Enter')
  await r1().waitFor()
  assert.equal(await d().count(),0)
  await r1().fill('2')
  await checkRoots().click()
  await page.getByRole('status').filter({hasText:'Введи оба корня.'}).waitFor()
  await r2().fill('2')
  await checkRoots().click()
  assert.equal(await page.getByRole('heading',{name:'Прокладываю маршрут…',exact:true}).count(),0)
  await r1().fill('3')
  await r2().fill('2')
  await noOverflow()
  await checkRoots().click()
  await page.getByRole('heading',{name:'Прокладываю маршрут…',exact:true}).waitFor()
  assert.equal(await checkRoots().count(),0)
  assert.equal(await page.getByRole('button',{name:/Тест:/}).count(),0)
  await page.getByRole('heading',{name:'Курс на планету',exact:true}).waitFor()
  assert.equal(await d().inputValue(),'')
  assert.equal(await page.locator('.full-solution').count(),0)
  assert.equal(await page.locator('.practice-hints').count(),0)
  await page.getByRole('button',{name:'Подсказка',exact:true}).click()
  await d().fill('16')
  await checkD().click()
  await r1().fill('1')
  await r2().fill('3')
  await checkRoots().click()
  await page.getByRole('heading',{name:'Маршрут восстановлен!',exact:true}).waitFor()
  await page.getByText('Самостоятельно, без полного разбора:',{exact:false}).filter({hasText:'1 из 2'}).waitFor()
  assert.equal(await page.getByText(/Подсказки использованы/).count(),0)
  await scan()
  await page.getByRole('button',{name:'Пройти снова',exact:true}).click()
  await page.getByRole('heading',{name:'Первая точка маршрута'}).waitFor()
  assert.equal(await d().inputValue(),'')
  assert.equal(await page.locator('.full-solution').count(),0)
  for(let i=0;i<2;i++){
    await d().fill(i===0?'1':'16')
    await checkD().click()
    await r1().fill(i===0?'2':'1')
    await r2().fill('3')
    await checkRoots().click()
    if(i===0)await page.getByRole('heading',{name:'Курс на планету',exact:true}).waitFor()
    else await page.getByRole('heading',{name:'Маршрут восстановлен!',exact:true}).waitFor()
  }
  await page.getByText('Самостоятельно, без полного разбора:',{exact:false}).filter({hasText:'2 из 2'}).waitFor()
  await page.getByRole('button',{name:'Повторить теорию'}).click()
  await page.getByRole('heading',{name:'Узнай коэффициенты'}).waitFor()
  assert.ok(await next().isDisabled())
  assert.equal(await page.locator('input:checked').count(),0)
  assert.equal(await page.locator('vite-error-overlay').count(),0)
  assert.deepEqual(errors,[])

})
